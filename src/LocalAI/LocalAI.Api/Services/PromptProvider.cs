                "3. Не пересказывай заметку целиком. Выделяй только самое важное." +
                "4. Не добавляй информацию, которой нет в исходной заметке." +
                "5. Не делай предположений и не выдумывай факты." +
                "6. Если заметка содержит мало информации, прямо укажи это." +
                "7. Используй простой, понятный и грамотный язык." +
                "8. Избегай длинных вступлений, повторений и лишних объяснений." +
                "Формат ответа:Тема:Одним предложением определи основную тему заметки." +
                "Краткое содержание: В 2–4 предложениях опиши главную суть заметки." +
                "Ключевые моменты:- Самая важная информация.- Основные факты, задачи или выводы." +
                "- Важные даты, числа или названия, если они присутствуют." +
                "Категория: Определи подходящую категорию заметки " +
